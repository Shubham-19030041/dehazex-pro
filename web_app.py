@app.route("/api/models")
def api_models():
    available = {name: os.path.exists(os.path.join(SAVE_DIR, fn))
                 for name, fn in MODEL_KEYS.items()}
    available[DCP_NAME] = True  # classical method, always available
    return jsonify(available)


@app.route("/api/dehaze", methods=["POST"])
def api_dehaze():
    file = request.files.get("image")
    model_choice = request.form.get("model", "Attention-UNet")
    auto_select = request.form.get("auto_select", "false") == "true"

    if file is None:
        return jsonify({"error": "No image uploaded"}), 400

    hazy, original_size = decode_upload(file)
    weather = detect_weather(hazy)
    density = haze_density(hazy)

    processed = preprocess_for_weather(hazy, weather)

    if auto_select:
        model_choice = {
            "aod_net": "AOD-Net",
            "attention_unet": "Attention-UNet",
            "gan_generator": "GAN",
        }[recommend_model(hazy)]
        # DCP is intentionally excluded from Auto Select — it's offered as a
        # manual classical baseline for comparison, not a recommended default.

    try:
        dehazed, elapsed_ms = run_model(model_choice, processed)
    except FileNotFoundError as e:
        return jsonify({"error": str(e)}), 400

    # Self-referential metrics (no ground truth available for user uploads):
    # compare dehazed output against the input to report entropy/edge gains.
    metrics = compute_all_metrics(dehazed, hazy, elapsed_ms)

    return jsonify({
        "input_image": encode_image(hazy, original_size),
        "output_image": encode_image(dehazed, original_size),
        "model_used": model_choice,
        "weather": weather,
        "haze_density": density,
        "metrics": metrics,
    })


@app.route("/api/dehaze_all", methods=["POST"])
def api_dehaze_all():
    file = request.files.get("image")
    if file is None:
        return jsonify({"error": "No image uploaded"}), 400

    hazy, original_size = decode_upload(file)
    weather = detect_weather(hazy)
    processed = preprocess_for_weather(hazy, weather)

    results = {}
    for name in list(MODEL_KEYS.keys()) + [DCP_NAME]:
        try:
            dehazed, elapsed_ms = run_model(name, processed)
            metrics = compute_all_metrics(dehazed, hazy, elapsed_ms)
            results[name] = {
                "output_image": encode_image(dehazed, original_size),
                "metrics": metrics,
            }
        except FileNotFoundError as e:
            results[name] = {"error": str(e)}

    return jsonify({
        "input_image": encode_image(hazy, original_size),
        "weather": weather,
        "results": results,
    })


